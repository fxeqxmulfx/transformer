#!/usr/bin/env python3
"""Encode the completed optimizer benchmark's logged binary64 values in Lean.

The Lean kernel checks arithmetic on this table. It does not verify the GPU
execution that produced the input. --check validates the extraction boundary
without rewriting the generated file. Run from any working directory.
"""

import argparse
import hashlib
import json
import math
import subprocess
from fractions import Fraction
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
LOG = ROOT / "experiments/archive/gpt_mini/optimizer_benchmark/results/rtx3050/runs.jsonl"
OUT = ROOT / "src/Transformer/OptimizerBenchmark/Basic.lean"
PROTOCOL = "566657d26031eb933ac6f3ea1897691c4077ce77e03f37956f39760d72b8e801"
ATTENTION = ("softmax", "sparsemax")
METHODS = (
    "sgd", "adagrad", "adam", "adamw", "amsgrad", "amsgrad_inverse",
    "amsgrad_geometric", "adamx", "adamnc", "muon", "muon_guarded",
    "dash_evd", "dash_ndb", "dash_cn", "dash_chebyshev", "dash_ndb_guarded",
    "adafisher", "adafisherw",
)
# The measured sources left the tree: the benchmark's modules, recorded by
# absolute path, are read where the last commit holding them archived them
# (python/README.md, Ports), and the reference model where it moved.
SOURCES = "2aec5b9"
ARCHIVED = "legacy/gpt_mini/src/infrastructure/benchmark/archive/experiments/"
MOVED = {"experiments/gpt_mini.py": "experiments/archive/gpt_mini/gpt_mini.py"}


def measured_source(name):
    """The bytes of a source the benchmark recorded under `name`."""
    if Path(name).is_absolute():
        path = ARCHIVED + name.rsplit("/experiments/", 1)[1]
        return subprocess.run(["git", "-C", str(ROOT), "show", f"{SOURCES}:{path}"],
                              capture_output=True, check=True).stdout
    return (ROOT / MOVED.get(name, name)).read_bytes()


def extract():
    raw = LOG.read_bytes()
    records = [json.loads(line) for line in raw.splitlines()]
    final = [r for r in records if r["phase"] == "final"]
    expected = {(a, m, s) for a in ATTENTION for m in METHODS for s in range(3)}
    actual = [(r["attention"], r["method"], r["seed"]) for r in final]
    if len(actual) != len(expected) or set(actual) != expected:
        raise ValueError("Expected exactly one final run per attention/method/seed")
    table = {}
    for r, key in zip(final, actual):
        if (r["status"] != "ok" or r["steps"] != 1000 or
                r["completed_steps"] != 1000 or r["protocol_sha256"] != PROTOCOL):
            raise ValueError(f"Incomplete or incompatible record: {key}")
        if not isinstance(r["test_loss"], float) or not math.isfinite(r["test_loss"]):
            raise ValueError(f"Invalid logged loss: {key}")
        table[key] = Fraction.from_float(r["test_loss"])
    # Check the shared experiment setup at the extraction boundary.
    for s in range(3):
        group = [r for r in final if r["seed"] == s]
        for field in ("initial_sha256", "batch_sha256"):
            if len({r[field] for r in group}) != 1:
                raise ValueError(f"Unpaired seed {s}: {field}")
    for a in ATTENTION:
        for m in METHODS:
            if len({r["lr"] for r in final if r["attention"] == a and r["method"] == m}) != 1:
                raise ValueError(f"Inconsistent selected rate: {a}/{m}")
    summary = json.loads((LOG.parent / "summary.json").read_text())
    rows = summary["methods"]
    pairs = {(a, m) for a in ATTENTION for m in METHODS}
    if len(rows) != len(pairs) or {(r["attention"], r["method"]) for r in rows} != pairs:
        raise ValueError("Summary does not contain all 36 complete method groups")
    for r in rows:
        a, m = r["attention"], r["method"]
        mean = sum(table[a, m, s] for s in range(3)) / 3
        if (not r["complete"] or r["successful_seeds"] != 3 or
                r["test_loss_mean"] != float(mean)):
            raise ValueError(f"Summary mean differs from exact final losses: {a}/{m}")
    metadata = json.loads((LOG.parent / "metadata.json").read_text())
    if metadata["protocol_sha256"] != PROTOCOL:
        raise ValueError("Benchmark metadata has a different protocol fingerprint")
    for name, expected_hash in metadata["protocol"]["source_hashes"].items():
        if hashlib.sha256(measured_source(name)).hexdigest() != expected_hash:
            raise ValueError(f"Frozen measured source has changed: {name}")
    return table, hashlib.sha256(raw).hexdigest()


def render(table, digest):
    lines = [
        "/-", "# Exact logged measurements of the optimizer benchmark", "",
        "Generated by scripts/optimizer_benchmark_data.py; do not edit by hand.",
        "Source: experiments/archive/gpt_mini/optimizer_benchmark/results/rtx3050/runs.jsonl,",
        "final runs only: 1000 updates, seeds 0, 1, 2, all 18 methods.",
        "Each rational is the exact value of the JSON number parsed as binary64,",
        "not its rounded printed decimal or an exact real-arithmetic model loss.",
        "The input log and GPU execution are outside the Lean trust boundary.", "",
        f"Raw log SHA256: {digest}",
        f"Protocol SHA256: {PROTOCOL}", "",
        "Algorithm references: Muon, arXiv:2502.16982, Section 2.2;",
        "DASH, arXiv:2602.02016v2, Sections 2-4. These measurements are our",
        "user-requested experiment; they are not claims or data from those papers.",
        "-/", "", "import Mathlib.Data.Fin.VecNotation",
        "import Mathlib.Data.Rat.Defs", "", "namespace Transformer.OptimizerBenchmark", "",
        "/-- Attention modes in REPORT.md, Protocol; the Sparsemax change concerns",
        "the attention map, not convexity of joint training. Related optimizer",
        "source: arXiv:2502.16982, Section 2.2. -/",
        "inductive Attention where", "  | softmax | sparsemax", "  deriving DecidableEq", "",
        "/-- Every method in REPORT.md, Implementation and proof scope. Source",
        "algorithms: arXiv:2502.16982, Section 2.2, and arXiv:2602.02016v2,",
        "Sections 2-4; proof status does not filter this empirical ranking. -/",
        "inductive Method where",
    ]
    for start in range(0, len(METHODS), 3):
        lines.append("  | " + " | ".join(METHODS[start:start + 3]))
    lines.extend([
        "  deriving DecidableEq", "",
        "/-- Final logged test cross-entropy, indexed by the actual seed number.",
        "Source: REPORT.md, Protocol and results; runs.jsonl, phase=final.",
        "These are exact encodings of measured outputs, not optimizer axioms.",
        "Algorithm references: arXiv:2502.16982, Section 2.2, and",
        "arXiv:2602.02016v2, Sections 2-4. -/",
        "def seedLoss : Attention → Method → Fin 3 → ℚ",
    ])
    for a in ATTENTION:
        for m in METHODS:
            values = [table[a, m, s] for s in range(3)]
            literals = [f"{v.numerator} / {v.denominator}" for v in values]
            lines.append(f"  | .{a}, .{m} =>")
            lines.append("      ![" + ", ".join(literals) + "]")
    lines.extend([
        "", "/-- Exact arithmetic mean of the three encoded measurements, before",
        "the reporting script's final binary64 rounding. Source: REPORT.md,",
        "Protocol, with algorithms from arXiv:2502.16982, Section 2.2, and",
        "arXiv:2602.02016v2, Sections 2-4. -/",
        "def meanLoss (attention : Attention) (method : Method) : ℚ :=",
        "  (seedLoss attention method 0 + seedLoss attention method 1 +",
        "    seedLoss attention method 2) / 3", "",
        "end Transformer.OptimizerBenchmark", "",
    ])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    table, digest = extract()
    content = render(table, digest)
    if args.check:
        if not OUT.exists() or OUT.read_text() != content:
            raise SystemExit("Generated Lean measurements differ from the final run log")
        print(f"Verified 108 exact loss encodings; raw log SHA256 {digest}")
    else:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(content)
        print(f"Wrote {OUT.relative_to(ROOT)} with 108 exact loss encodings")


if __name__ == "__main__":
    main()
