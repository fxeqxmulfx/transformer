"""Export the full captured trace and independently checked Lean proofs (L3).

Only exact rational literals and ordinary proof scripts are emitted. All
polynomial and algebraic premises are rechecked by Lean. Run through run.py.
"""

from fractions import Fraction as Q
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEST = Path("src/Transformer/SequenceModel/Attention/Backend/Complete")
PREFIX = "Transformer.SequenceModel.Attention.Backend.Complete"


def scalar(x):
    x = Q(x)
    return f"({x.numerator} / {x.denominator} : ℝ)"


def array(xs):
    return "![" + ", ".join(xs) + "]"


def vector(xs):
    return "WithLp.toLp 2 " + array([scalar(x) for x in xs])


def rows(record):
    n = record["shape"][-1]
    return [record["values"][i:i+n] for i in range(0, len(record["values"]), n)]


def module(imports, title, body):
    return f'''module

{chr(10).join('public import ' + x for x in imports)}

/-!
# {title}

Source: `review/flat_spectrum.md`, *Complete captured execution*, L3.
Generated by `./run.py model-trace-certificates` from the frozen capture and
rational witnesses. These statements concern one recorded CUDA invocation.
-/

@[expose] public section
noncomputable section

namespace {PREFIX}

open GPTMini Stability Execution
open scoped BigOperators

set_option maxRecDepth 4096
set_option maxHeartbeats 2000000

{body}
end {PREFIX}
'''


def render(capture, certificates):
    result = {}
    p, t, witnesses = capture["parameters"], capture["trace"], certificates["witnesses"]
    body = '''/-- The actual source dimensions, including its width-eleven SwiGLU. -/
abbrev cfg : Config := { witnessConfig with
  n_layers := 1
  max_seq_len := 2
  n_layers_pos := by decide
  max_seq_len_pos := by decide }

'''
    fc = rows(p["blocks.0.ffwd.c_fc.weight"])
    matrices = [("qkv", rows(p["blocks.0.sa.c_attn.weight"])),
                ("projection", rows(p["blocks.0.sa.c_proj.weight"])),
                ("gate", fc[:11]), ("value", fc[11:]),
                ("output", rows(p["blocks.0.ffwd.c_proj.weight"]))]
    for name, matrix in matrices:
        body += f"/-- Exact stored {name} matrix in output-row/input-column order. -/\ndef matrix_{name} : Matrix (Fin {len(matrix)}) (Fin {len(matrix[0])}) ℝ := " + array([array([scalar(x) for x in row]) for row in matrix]) + "\n\n"
    body += "/-- Exact decoded checkpoint weights, including all five independent matrices. -/\ndef blockWeights : Attention.BlockParams cfg where\n"
    for name, matrix in matrices:
        body += f"  {name} := matrixEquiv _ _ matrix_{name}\n"
    for name, matrix in matrices:
        body += f"\n/-- L3: the stored {name} map acts by its exact matrix coordinates. -/\ntheorem apply_{name} (x : EucSpace {len(matrix[0])}) : blockWeights.{name} x = WithLp.toLp 2 (fun r => ∑ c, matrix_{name} r c * x c) := rfl\n"
    body += '\n/-- The actual tied embedding and one active block. -/\ndef weights : Attention.ModelParams cfg where\n'
    body += "  embedding := " + array([vector(row) for row in rows(p["token_embedding_table.weight"])]) + "\n"
    body += "  blocks := ![blockWeights]\n\n/-- The captured input word. -/\ndef tokens : Fin 2 → Fin cfg.vocab_size := ![0, 1]\n\n"
    body += "/-- Exact source geometric RoPE phases, not rounded table values. -/\ndef angles := sourceAngles cfg ![true] (fun i : Fin 2 => (i.val : ℝ))\n"
    result[DEST / "Parameters.lean"] = module([PREFIX + ".Averages"], "Captured source checkpoint", body)
    body = ""
    for name, record in t.items():
        data = array([vector(row) for row in rows(record)])
        body += f"/-- Exact binary output at the {name} operation. -/\ndef raw_{name} : Fin 2 → EucSpace {record['shape'][-1]} := {data}\n\n"
    for name, record in capture["tables"].items():
        body += f"/-- Source stored {name} table, built in float32. -/\ndef raw_{name} : Fin 2 → Fin 2 → ℝ := " + array([array([scalar(x) for x in row]) for row in rows(record)]) + "\n\n"
    for name, part in (("qPart", "qkvQ"), ("kPart", "qkvK"), ("vPart", "qkvV")):
        body += f"/-- Exact source reshape of the captured fused tensor. -/\ndef {name} (i : Fin 2) : EucSpace 4 := headSlice cfg (qkvSlice cfg ({part} cfg) (raw_fused i)) 0\n\n"
    result[DEST / "Recorded.lean"] = module([PREFIX + ".Parameters"], "Exact recorded intermediate tensors", body)
    body = '''/-- All recorded attention operation boundaries with the actual source layout. -/
def attnTrace : AttentionTrace cfg 2 where
  pre := raw_pre
  fused := raw_fused
  qnorm := ![raw_qnorm]
  knorm := ![raw_knorm]
  cosTable := raw_cos
  sinTable := raw_sin
  query := ![raw_query]
  key := ![raw_key]
  scores := ![fun i j => raw_scores i j]
  average := fun i => ![raw_average i]
  direction := fun i => ![raw_direction i]
  heads := fun i => ![raw_heads i]
  projected := raw_projected
  output := raw_attn_output

/-- L3: the one-head merge retains every stored channel in source order. -/
theorem merge_heads (i : Fin 2) : headMerge cfg (attnTrace.heads i) = raw_heads i := by
  ext c
  fin_cases c <;> rfl

/-- All recorded SwiGLU operation boundaries. -/
def ffnTrace : FFNTrace cfg 2 where
  pre := raw_ffn_pre
  gate := raw_gate
  value := raw_value
  activated := raw_activated
  product := raw_product
  projected := raw_ffn_projected
  output := raw_ffn_output

/-- Actual sequential residual additions link the two branches. -/
def blockTrace : BlockTrace cfg 2 where
  attn := attnTrace
  mid := raw_mid
  ffn := ffnTrace
  output := raw_output

/-- Complete finite CUDA trace, from stored embedding through tied logits. -/
def captured : ModelTrace cfg 2 where
  embedding := weights.embedding
  initial := raw_initial
  blocks := ![blockTrace]
  normalized := raw_normalized
  logits := fun i v => raw_logits i v
'''
    result[DEST / "Trace.lean"] = module([PREFIX + ".Recorded"], "Complete captured ModelTrace", body)
    links = [("initial", "weights.embedding (tokens i)", "weights, tokens"),
             ("pre", "raw_initial i", "raw_initial"), ("qnorm", "qPart i", "qPart"),
             ("knorm", "kPart i", "kPart"), ("direction", "vPart i", "vPart"),
             ("attn_output", "raw_projected i", "raw_projected"),
             ("ffn_pre", "raw_mid i", "raw_mid"), ("ffn_output", "raw_ffn_projected i", "raw_ffn_projected"),
             ("normalized", "raw_output i", "raw_output")]
    for group, subset in (("NormInputs", links[:5]), ("NormOutputs", links[5:])):
        body = ""
        for name, x, unfold in subset:
            l2 = name == "direction"
            target = f"normL2 (1 / 1000000000000) ({x})" if l2 else f"rmsNormEps (1 / 8388608) ({x})"
            scales = array([scalar(s) for s in witnesses[name]])
            simp = f"{unfold}, raw_{name}, raw_fused, headSlice, qkvSlice, headSplit, qkvQ, qkvK, qkvV, qkvSplit, finSumFinEquiv, finProdFinEquiv, cfg, Config.head_dim, Fin.sum_univ_succ"
            body += f'''/-- L3: the captured {name} calls satisfy their source normalizer contract. -/
theorem checked_{name} (i : Fin 2) : ‖raw_{name} i - {target}‖ ≤ 1 / 10000 := by
  apply {"l2_checked" if l2 else "rms_checked"} _ _ ({scales} i)
  · fin_cases i <;> norm_num
'''
            if l2:
                body += f"  · fin_cases i <;> norm_num [{simp}]\n"
            body += f"  · fin_cases i <;> norm_num [{simp}]\n  · intro c\n    fin_cases i <;> fin_cases c <;> norm_num [{simp}]\n\n"
        result[DEST / f"{group}.lean"] = module([PREFIX + ".Trace"], "Checked normalizer operations", body)
    arithmetic = [
        ("fused", "blockWeights.qkv (raw_pre i)", "blockWeights, raw_pre"),
        ("projected", "blockWeights.projection (headMerge cfg (attnTrace.heads i))", "raw_heads"),
        ("gate", "blockWeights.gate (raw_ffn_pre i)", "blockWeights, raw_ffn_pre"),
        ("value", "blockWeights.value (raw_ffn_pre i)", "blockWeights, raw_ffn_pre"),
        ("product", "WithLp.toLp 2 (fun c => raw_activated i c * raw_value i c)", "raw_activated, raw_value"),
        ("ffn_projected", "blockWeights.output (raw_product i)", "blockWeights, raw_product"),
        ("mid", "raw_initial i + raw_attn_output i", "raw_initial, raw_attn_output"),
        ("output", "raw_mid i + raw_ffn_output i", "raw_mid, raw_ffn_output"),
        ("query", "tableRotate 4 (raw_cos i) (raw_sin i) (raw_qnorm i)", "table_four, raw_cos, raw_sin, raw_qnorm"),
        ("key", "tableRotate 4 (raw_cos i) (raw_sin i) (raw_knorm i)", "table_four, raw_cos, raw_sin, raw_knorm"),
        ("heads", "(if i.val = 0 then 0 else raw_average i - inner ℝ (raw_average i) (raw_direction i) • raw_direction i)", "raw_average, raw_direction, EuclideanSpace.inner_eq_star_dotProduct, dotProduct"),
    ]
    for group, subset in (("Linear", arithmetic[:6]), ("Arithmetic", arithmetic[6:])):
        body = ""
        for name, x, unfold in subset:
            learned = {"fused": "qkv", "projected": "projection", "gate": "gate", "value": "value", "ffn_projected": "output"}.get(name)
            prefix = f"  rw [apply_{learned}]\n" if learned else ("  rw [table_four]\n" if name in ("query", "key") else "")
            if name == "projected":
                prefix += "  rw [merge_heads]\n"
            unfold = unfold.replace("blockWeights, ", "")
            if learned:
                unfold += f", matrix_{learned}"
            body += f'''/-- L3: captured {name} arithmetic is checked at its own stored inputs. -/
theorem checked_{name} (i : Fin 2) : ‖raw_{name} i - ({x})‖ ≤ 1 / 10000 := by
{prefix}  apply vector_checked (by decide)
  intro c
  fin_cases i <;> fin_cases c <;>
    norm_num [{unfold}, raw_{name}, finSumFinEquiv, finProdFinEquiv, Fin.sum_univ_succ]

'''
        result[DEST / f"{group}.lean"] = module([PREFIX + ".Trace"], "Checked rational operation residuals", body)
    body = '''/-- L3: auxiliary SDPA scores satisfy the actual scaled dot-product contract. -/
theorem checked_scores (i j : Fin 2) :
    |raw_scores i j - inner ℝ (raw_query i) (raw_key j) / Real.sqrt (4 : ℝ)| ≤ 1 / 10000 := by
  fin_cases i <;> fin_cases j <;>
    norm_num [raw_scores, raw_query, raw_key, EuclideanSpace.inner_eq_star_dotProduct,
      dotProduct, Fin.sum_univ_succ]

/-- L3: the final raw tied matrix product is checked independently. -/
theorem checked_logits (i : Fin 2) (v : Fin 3) :
    |raw_logits i v - inner ℝ (raw_normalized i) (weights.embedding v)| ≤ 1 / 10000 := by
  fin_cases i <;> fin_cases v <;>
    norm_num [raw_logits, raw_normalized, weights, EuclideanSpace.inner_eq_star_dotProduct,
      dotProduct, Fin.sum_univ_succ]

/-- L3: both stored source positions have certified independent cosine/sine errors. -/
theorem checked_tables (i : Fin 2) (c : Fin 2) :
    |raw_cos i c - Real.cos (angles 0 i c)| ≤ 2 / 1000000 ∧
    |raw_sin i c - Real.sin (angles 0 i c)| ≤ 2 / 1000000 := by
  fin_cases i
  · fin_cases c <;> norm_num [raw_cos, raw_sin, angles, sourceAngles]
  · have h := rope_fixture (raw_cos 1) (raw_sin 1)
      (by intro k; fin_cases k <;> norm_num [raw_cos, rotationPolynomial,
        Finset.sum_range_succ, pow_succ, Complex.mul_re, Complex.mul_im])
      (by intro k; fin_cases k <;> norm_num [raw_sin, rotationPolynomial,
        Finset.sum_range_succ, pow_succ, Complex.mul_re, Complex.mul_im]) c
    simpa [angles, sourceAngles, cfg, Config.head_dim] using h
'''
    result[DEST / "Scalars.lean"] = module([PREFIX + ".Trace"], "Checked scores, readout and source RoPE", body)
    body = ""
    for i in range(2):
        e = array([scalar(s) for s in witnesses[f"activated.{i}"]])
        body += f'''/-- L3: all captured SiLU outputs at token {i} have polynomial certificates. -/
theorem checked_activated_{i} :
    ‖raw_activated {i} - WithLp.toLp 2 (fun c => Landscape.Neural.silu (raw_gate {i} c))‖ ≤ 1 / 10000 := by
  apply silu_vector_checked (by decide) _ _ {e}
  · intro c; fin_cases c <;> norm_num [raw_gate]
  · intro c; fin_cases c <;> norm_num
  · intro c; fin_cases c <;> norm_num [raw_gate, expPolynomial, Finset.sum_range_succ]
  · intro c; fin_cases c <;> norm_num [raw_gate, raw_activated]

'''
    result[DEST / "Activations.lean"] = module([PREFIX + ".Trace"], "Checked captured SwiGLU activations", body)
    body = ""
    for i in range(2):
        e = array([scalar(s) for s in witnesses[f"average.{i}"]])
        body += f'''/-- L3: the captured SDPA row {i} is certified at its stored scores and values. -/
theorem checked_average_{i} :
    ‖raw_average {i} - ∑ j, causalWeight (fun a b => raw_scores a b) {i} j • vPart j‖ ≤ 1 / 10000 := by
  apply average_checked (fun a b => raw_scores a b) {i} {e}
  · intro j hj; fin_cases j <;> norm_num [raw_scores] at *
  · intro j hj; fin_cases j <;> norm_num [raw_scores, expPolynomial, Finset.sum_range_succ] at *
  · simp only [Fin.sum_univ_succ]; norm_num
  · intro j c; fin_cases j <;> fin_cases c <;>
      norm_num [vPart, raw_fused, headSlice, qkvSlice, headSplit, qkvV, qkvSplit, finSumFinEquiv, finProdFinEquiv, cfg, Config.head_dim]
  · intro c; fin_cases c <;> simp only [Fin.sum_univ_succ] <;>
      norm_num [raw_average, vPart, raw_fused, headSlice, qkvSlice, headSplit, qkvV, qkvSplit, finSumFinEquiv, finProdFinEquiv, cfg, Config.head_dim]

'''
    result[DEST / "Softmax.lean"] = module([PREFIX + ".Trace"], "Checked captured causal attention averages", body)
    return result


def main():
    capture = json.loads((ROOT / "review/model_trace_capture.json").read_text())
    certificates = json.loads((ROOT / "review/model_trace_certificates.json").read_text())
    for path, text in render(capture, certificates).items():
        (ROOT / path).write_text(text)
        print(path)


if __name__ == "__main__":
    main()
