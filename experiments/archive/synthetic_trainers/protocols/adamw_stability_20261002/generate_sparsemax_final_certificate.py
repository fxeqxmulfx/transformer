"""Generate lossless Lean data from the actual final CPU prediction tables."""

import csv
import hashlib
import json
from pathlib import Path


ARCHIVE = Path("experiments/synthetic_trainers/baselines/adamw_sparsemax_final_certificate_20261003")
TARGET = Path("src/Transformer/GPTMini/Sparsemax/Certificate")
EXPECTED = {
    "train": "85a1ba18e80d6b54b41f38a6387a04f2001c50863bed897aa4118c3d3915e82d",
    "heldout": "0861dd669f55d44cfa30f687721d665b5eefa68bd8e39a62866e9959c052fe49",
}


def load_rows(partition):
    path = ARCHIVE / f"{partition}-predictions.csv"
    assert hashlib.sha256(path.read_bytes()).hexdigest() == EXPECTED[partition]
    with path.open(newline="") as stream:
        reader = csv.DictReader(stream)
        assert reader.fieldnames == ["numerator", "denominator", "predicted_answer", "EOS_correct"]
        rows = [tuple(map(int, row.values())) for row in reader]
    codes = []
    for numerator, denominator, prediction, eos in rows:
        assert 0 <= numerator < 193 and 0 < denominator < 193
        assert 0 <= prediction < 194 and eos in (0, 1)
        code = ((numerator * 193 + denominator) * 194 + prediction) * 2 + eos
        decoded = (code // 2 // 194 // 193, code // 2 // 194 % 193, code // 2 % 194, code % 2)
        assert decoded == (numerator, denominator, prediction, eos)
        codes.append(code)
    measured = json.loads((ARCHIVE / "CPU-export-validation.json").read_text())["predictions"][partition]
    correct = sum(prediction < 193 and eos == 1 and denominator * prediction % 193 == numerator
                  for numerator, denominator, prediction, eos in rows)
    assert len(rows) == measured["examples"] and correct == measured["correct_complete_RHS"]
    return [codes[start:start + 128] for start in range(0, len(codes), 128)]


def write_data(module, name, batches, partition):
    body = ",\n".join("  [" + ", ".join(map(str, batch)) + "]" for batch in batches)
    source = f'''import Transformer.GPTMini.Sparsemax.Certificate.Basic

/-!
# Actual final-checkpoint {partition} prediction records

Generated by `generate_sparsemax_final_certificate.py` from the archived
CSV, SHA256 {EXPECTED[partition]}.
Checkpoint SHA256:
c3f296b2f9ffd388451f4beefb358b184ad32da404658424c6685c9a935ac601.
Source context: arXiv:2211.11052v1, §4, modular division; prime-193
experiment adaptation. Packing retains every numeral and EOS flag.
-/

namespace Transformer.GPTMini.Sparsemax.Certificate

set_option maxRecDepth 200000
set_option maxHeartbeats 0

/-- Losslessly packed actual {partition} rows, in frozen corpus order.
Source: §4's division task, final 300000-update sparsemax checkpoint,
CPU export recorded at 2026-10-03T06:45:16Z. -/
def {name} : List (List ℕ) := [
{body}]

end Transformer.GPTMini.Sparsemax.Certificate
'''
    (TARGET / f"{module}.lean").write_text(source)


def main():
    train, heldout = load_rows("train"), load_rows("heldout")
    TARGET.mkdir(parents=True, exist_ok=True)
    write_data("Train", "trainPredictions", train, "train")
    write_data("HeldoutFirst", "heldoutFirstPredictions", heldout[:109], "heldout")
    write_data("HeldoutLast", "heldoutLastPredictions", heldout[109:], "heldout")
    print(json.dumps({"train_rows": sum(map(len, train)), "heldout_rows": sum(map(len, heldout)),
                      "lossless_roundtrip_checked": True, "CSV_hashes": EXPECTED}))


if __name__ == "__main__":
    main()
