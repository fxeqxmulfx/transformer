//! Generate INDEX.md from checked Lean artifacts without invoking Python.
mod scan;
use scan::{Declaration, Incomplete, Scanner};
use std::{collections::BTreeMap, error::Error, fs, path::Path, process::Command};

type Result<T> = std::result::Result<T, Box<dyn Error>>;

struct Module {
    name: String,
    path: String,
    lines: usize,
    declarations: Vec<Declaration>,
}

fn lean(args: &[&str]) -> Result<String> {
    let output = Command::new("lake")
        .env("LAKE_ARTIFACT_CACHE", "false")
        .args(args)
        .output()?;
    if !output.status.success() {
        return Err(format!(
            "lake {} failed:\n{}\n{}",
            args.join(" "),
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        )
        .into());
    }
    Ok(String::from_utf8(output.stdout)?)
}

fn files(path: &Path, out: &mut Vec<String>) -> Result<()> {
    let mut entries = fs::read_dir(path)?.collect::<std::io::Result<Vec<_>>>()?;
    entries.sort_by_key(|e| e.file_name());
    for entry in entries {
        let path = entry.path();
        if entry.file_type()?.is_dir() {
            files(&path, out)?;
        } else if path.extension().is_some_and(|e| e == "lean") {
            out.push(path.to_str().ok_or("non-UTF-8 source path")?.to_owned());
        }
    }
    Ok(())
}

fn namespace(path: &str) -> String {
    let parts: Vec<_> = path
        .trim_start_matches("src/")
        .trim_end_matches(".lean")
        .split('/')
        .collect();
    match parts.as_slice() {
        ["Transformer"] | [_, "Basic"] => "Transformer".into(),
        [name] | [_, name] => format!("Transformer.{name}"),
        _ => parts[..parts.len() - 1].join("."),
    }
}

fn main() -> Result<()> {
    let args: Vec<_> = std::env::args().skip(1).collect();
    let (output, check) = match args.as_slice() {
        [] => ("INDEX.md", false),
        [flag] if flag == "--check" => ("INDEX.md", true),
        [flag, path] if flag == "--output" => (path.as_str(), false),
        _ => {
            return Err(
                "usage: lean-index [--check | --output PATH]; run from the repository root".into(),
            );
        }
    };
    lean(&["build"])?;
    let mut incomplete = Incomplete::new();
    for row in lean(&["env", "lean", "scripts/Sorries.lean"])?.lines() {
        let fields: Vec<_> = row.split('\t').collect();
        if fields.len() != 3 {
            return Err(format!("unexpected sorry-audit output: {row}").into());
        }
        incomplete.insert(
            (fields[0].to_owned(), fields[1].parse()?),
            fields[2].to_owned(),
        );
    }
    let scanner = Scanner::new();
    let mut paths = Vec::new();
    files(Path::new("src"), &mut paths)?;
    let mut subjects: BTreeMap<String, Vec<Module>> = BTreeMap::new();
    let mut papers = BTreeMap::new();
    for path in paths {
        let source = fs::read_to_string(&path)?;
        let (declarations, paper) = scanner.scan(&path, &source, &mut incomplete);
        let ns = namespace(&path);
        if let Some(paper) = paper {
            papers.entry(ns.clone()).or_insert(paper);
        }
        subjects.entry(ns).or_default().push(Module {
            name: path
                .trim_start_matches("src/")
                .trim_end_matches(".lean")
                .replace('/', "."),
            lines: source.bytes().filter(|&b| b == b'\n').count(),
            path,
            declarations,
        });
    }
    if !incomplete.is_empty() {
        return Err(format!("sorry outside every indexed declaration: {incomplete:?}").into());
    }
    for modules in subjects.values_mut() {
        modules.sort_by(|a, b| a.name.cmp(&b.name));
    }
    let everything: Vec<_> = subjects
        .values()
        .flatten()
        .flat_map(|m| &m.declarations)
        .collect();
    let counts = |ds: &[&Declaration], status| ds.iter().filter(|d| d.status == status).count();
    let theorems = |ds: &[&Declaration]| {
        ds.iter()
            .filter(|d| matches!(d.kind.as_str(), "theorem" | "lemma"))
            .count()
    };
    let modules = subjects.values().map(Vec::len).sum::<usize>();
    let mut w = vec![
        "# Index".into(),
        "".into(),
        "Generated by `scripts/native_index` from `src/` and `lake build`; do not edit by hand."
            .into(),
        "".into(),
        format!(
            "{modules} modules · {} theorems · {} using `sorry` · {} concluding `True` · {} placeholder definitions.",
            theorems(&everything),
            counts(&everything, "sorry"),
            counts(&everything, "vacuous"),
            counts(&everything, "placeholder")
        ),
        "".into(),
        "`vacuous` and `placeholder` are the ones that do not show up in the sorry".into(),
        "count or in `#print axioms`; see [Gaps](#gaps).".into(),
        "".into(),
        "## Subjects".into(),
        "".into(),
        "| namespace | paper | modules | theorems | sorry | vacuous | placeholder |".into(),
        "| --- | --- | ---: | ---: | ---: | ---: | ---: |".into(),
    ];
    for (ns, ms) in &subjects {
        let ds: Vec<_> = ms.iter().flat_map(|m| &m.declarations).collect();
        let paper = papers.get(ns).map_or("—".into(), |p| format!("arXiv:{p}"));
        w.push(format!(
            "| [`{ns}`](#{}) | {paper} | {} | {} | {} | {} | {} |",
            ns.to_lowercase().replace('.', ""),
            ms.len(),
            theorems(&ds),
            counts(&ds, "sorry"),
            counts(&ds, "vacuous"),
            counts(&ds, "placeholder")
        ));
    }
    w.extend(["".into(), "## Declarations".into(), "".into()]);
    for (ns, ms) in &subjects {
        w.extend([format!("### `{ns}`"), "".into()]);
        for m in ms {
            if m.declarations.is_empty() {
                w.extend([
                    format!(
                        "**[{}]({})** — {} lines, aggregator",
                        m.name, m.path, m.lines
                    ),
                    "".into(),
                ]);
                continue;
            }
            w.extend([
                format!("**[{}]({})** — {} lines", m.name, m.path, m.lines),
                "".into(),
                "| declaration | kind | status |".into(),
                "| --- | --- | --- |".into(),
            ]);
            for d in &m.declarations {
                w.push(format!(
                    "| [`{}`]({}#L{}) | {} | {} |",
                    d.name, m.path, d.line, d.kind, d.status
                ));
            }
            w.push("".into());
        }
    }
    w.extend([
        "## Gaps".into(),
        "".into(),
        "Everything the build cannot vouch for, in one place.".into(),
        "".into(),
    ]);
    for (status, title) in [
        ("sorry", "Incomplete proofs (`sorry`)"),
        ("vacuous", "Vacuous statements (conclude `True`)"),
        ("placeholder", "Placeholder definitions"),
    ] {
        w.extend([
            format!("### {title} — {}", counts(&everything, status)),
            "".into(),
            "| declaration | kind | module |".into(),
            "| --- | --- | --- |".into(),
        ]);
        for m in subjects.values().flatten() {
            for d in m.declarations.iter().filter(|d| d.status == status) {
                w.push(format!(
                    "| [`{}`]({}#L{}) | {} | `{}` |",
                    d.name, m.path, d.line, d.kind, m.name
                ));
            }
        }
        w.push("".into());
    }
    let rendered = w.join("\n").trim_end().to_owned() + "\n";
    if check {
        if fs::read_to_string(output)? != rendered {
            return Err("INDEX.md is stale".into());
        }
    } else {
        fs::write(output, rendered)?;
    }
    println!(
        "{output}: {modules} modules, {} theorems, {} sorry, {} vacuous, {} placeholder",
        theorems(&everything),
        counts(&everything, "sorry"),
        counts(&everything, "vacuous"),
        counts(&everything, "placeholder")
    );
    Ok(())
}
