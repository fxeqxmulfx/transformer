"""Export exact captured binary values to ordinary Lean proofs, manuscript K6.

The export supplies literals and proof scripts, never axioms or native_decide.
Lean independently proves each numerical premise and analytic consequence.
Running ./run.py backend-certificates rewrites only these three generated
modules from the frozen JSON. Tests compare their exact text with the export.
"""

from fractions import Fraction
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DESTINATION = Path("src/Transformer/SequenceModel/Attention/Backend")


def literal(value):
    number = Fraction(value)
    return f"({number.numerator} / {number.denominator} : ℝ)"


def vector(values):
    return "![" + ", ".join(literal(value) for value in values) + "]"


def render(report):
    """Produce proof sources from data alone; no evaluation of PyTorch is involved."""
    result = {}
    for case, suffix, tag in zip(report["cases"], ("CPU32", "CPU64", "CUDA32"),
                                 ("cpu32", "cpu64", "cuda32"), strict=True):
        v = {name: vector(values) for name, values in case["outputs"].items()}
        silu = literal(case["outputs"]["silu"][0])
        text = f'''module

public import Transformer.SequenceModel.Attention.Backend.NormFixtures
public import Transformer.SequenceModel.Attention.Backend.ExpFixtures
public import Transformer.SequenceModel.Attention.Backend.RopeFixtures

/-!
# Exact captured {suffix} primitive certificates

Source: `review/flat_spectrum.md`, *Concrete backend contracts*, K6.
Generated by `./run.py backend-certificates` from `review/backend_contract_check.json`.
Backend: {case["device"]}, {case["dtype"]}, {case["compile"]}, SDPA MATH.
These are exact rational encodings of the captured finite binary outputs.
Lean checks all numerical premises; no native decision procedure is used.
The statements concern this recorded data, not unobserved kernel executions.
-/

@[expose] public section
noncomputable section

namespace Transformer.SequenceModel.Attention.Backend

open GPTMini Landscape.Neural
open scoped BigOperators

/-- K6: captured {suffix} RMSNorm error at the source float32 epsilon. -/
theorem captured_{tag}_rms :
    ‖(WithLp.toLp 2 {v["rms"]} : EucSpace 4) - rmsNormEps (1 / 8388608) normInput‖ ≤ 4 / 1000000 := by
  apply rms_fixture
  intro c
  fin_cases c <;> norm_num [normInput]

/-- K6: captured {suffix} clipped L2 output at the source epsilon. -/
theorem captured_{tag}_l2 :
    ‖(WithLp.toLp 2 {v["l2"]} : EucSpace 4) - normL2 (1 / 1000000000000) normInput‖ ≤ 3 / 1000000 := by
  apply l2_fixture
  intro c
  fin_cases c <;> norm_num [normInput]

/-- K6: captured {suffix} nonzero SiLU activation. -/
theorem captured_{tag}_silu : |{silu} - silu (1 / 2)| ≤ 2 / 1000000 := by
  apply silu_fixture
  norm_num [halfExp]

/-- K6: captured {suffix} nontrivial two-token causal SDPA row. -/
theorem captured_{tag}_sdpa :
    ‖(WithLp.toLp 2 {v["sdpa"]} : EucSpace 4) -
      ∑ j, causalWeight sdpaScores 1 j • sdpaValues j‖ ≤ 3 / 1000000 := by
  apply sdpa_fixture
  intro c
  fin_cases c <;> norm_num [sdpaReference, halfExp]

/-- K6: captured {suffix} source geometric RoPE coefficients, checked independently. -/
theorem captured_{tag}_rope : ∀ k : Fin 2,
    |{v["cos"]} k - Real.cos (invFreq 4 10000 k)| ≤ 2 / 1000000 ∧
    |{v["sin"]} k - Real.sin (invFreq 4 10000 k)| ≤ 2 / 1000000 := by
  apply rope_fixture
  · intro k
    fin_cases k <;> norm_num [rotationPolynomial, Finset.sum_range_succ,
      pow_succ, Complex.mul_re, Complex.mul_im]
  · intro k
    fin_cases k <;> norm_num [rotationPolynomial, Finset.sum_range_succ,
      pow_succ, Complex.mul_re, Complex.mul_im]

/-- K6: captured {suffix} matrix product equals its exact rational operation. -/
theorem captured_{tag}_matrix :
    (WithLp.toLp 2 {v["matrix"]} : EucSpace 2) =
      WithLp.toLp 2 (fun r => ∑ c : Fin 4,
        (!![(1 : ℝ), 1 / 2, -(1 / 4), 0; -1, 0, 1 / 8, 2]) r c * normInput c) := by
  ext r
  fin_cases r <;> norm_num [normInput, Fin.sum_univ_succ]

end Transformer.SequenceModel.Attention.Backend
'''
        result[DESTINATION / f"Captured{suffix}.lean"] = text
    return result


def main():
    report = json.loads((ROOT / "review/backend_contract_check.json").read_text())
    for path, text in render(report).items():
        (ROOT / path).write_text(text)
        print(path)


if __name__ == "__main__":
    main()
